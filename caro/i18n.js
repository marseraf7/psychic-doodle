      srv_invite_no_answer: '{name} 没有回应挑战',
      srv_waiting_opponent: '正在等待对手',
      srv_game_over: '本局已结束',
      srv_match_over: '比赛已结束',
      srv_not_your_turn: '还没轮到你',
      srv_bad_move: '无效的落子',
